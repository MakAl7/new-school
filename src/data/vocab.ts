export function splitVocab(v: VocabWord): [string, string] {
  const i = v.w.indexOf(".");
  return [v.w.slice(0, i), v.w.slice(i + 1)];
}

export function fullWord(v: VocabWord): string {
  const [pre, post] = splitVocab(v);
  return pre + v.a + post;
}

